// Це рядок і два числа, результат буде конкатенація рядка з числами.
console.log('number' + 3 + 3); // 'number33'

// null при додаванні до числа перетворюється на 0.
console.log(null + 3); // 3

// Оператор && повертає останнє значення, якщо всі умови істинні. Оскільки "qwerty" не є пустим рядком, результатом буде "qwerty".
console.log(5 && "qwerty"); // "qwerty"

// +'40' і +'2' перетворюються на числа (40 і 2). Тому спочатку відбудеться додавання 40 + 2 = 42, після чого конкатенується з "hillel".
console.log(+'40' + +'2' + "hillel"); // "42hillel"

// Спочатку відбудеться перетворення '10' на число (10). Потім 10 - 5 = 5, і результат порівняння 5 === 6 буде false.
console.log('10' - 5 === 6); // false

// true дорівнює 1, а false дорівнює 0, тому результатом буде 1 + 0 = 1.
console.log(true + false); // 1

// Строки з одиничними знаками не можна відняти від чисел, тому результат буде NaN (Not a Number).
console.log('4px' - 3); // NaN

// Строка '4' буде перетворена на число, і 4 - 3 = 1.
console.log('4' - 3); // 1

// 3 ** 0 дорівнює 1, тому результат буде '6' + 1, що дає '61'.
console.log('6' + 3 ** 0); // '61'

// Строка '6' буде перетворена на число 6, тому результат буде 12 / 6 = 2.
console.log(12 / '6'); // 2

// 5 === 6 дає false, тому '10' + false дає '10false'.
console.log('10' + (5 === 6)); // '10false'

// null не рівне порожньому рядку, тому результат буде false.
console.log(null == ''); // false

// 9 / 3 дорівнює 3, тому 3 ** 3 = 27.
console.log(3 ** (9 / 3)); // 27

// !!'false' і !!'true' обидва перетворюються в true, тому результат буде true == true, що дає true.
console.log(!!'false' == !!'true'); // true

// Оператор && має вищий пріоритет, тому спочатку '0' && 1 дасть 1. Далі 0 || 1 дасть 1.
console.log(0 || '0' && 1); // 1

// +null перетворюється на 0, тому порівняння 0 == false дає true (як 1). 1 < 1 дає false.
console.log((+null == false) < 1); // false

// Спочатку false && true дасть false. Потім false || true дасть true.
console.log(false && true || true); // true

// Спочатку false || true дасть true, але false && true дасть false.
console.log(false && (false || true)); // false

// +null == false дасть true, тобто 1 < 1 ** 5, де 1 ** 5 дорівнює 1. Результат 1 < 1 дасть false.
console.log((+null == false) < 1 ** 5); // false
